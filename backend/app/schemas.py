class VerificationJobResponse(BaseModel):
    id: str
    input_type: str
    raw_input: str
    detected_language: Dict[str, Any] = Field(default_factory=dict)
    primary_claim: str
    extracted_claims: List[ExtractedClaim] = Field(default_factory=list)
    fact_check_matches: List[ClaimReviewItem] = Field(default_factory=list)
    sources: List[SourceItem] = Field(default_factory=list)
    evidence: List[EvidenceRecord] = Field(default_factory=list)
    final_verdict: VerificationVerdict
    verdict: Optional[str] = None
    initial_verdict: str
    assessment_confidence: float = Field(default=0.8, ge=0.0, le=1.0)
    confidence: Optional[float] = None
    soundness_explanation: str
    explanation: Optional[str] = None
    verdict_summary: str
    summary: Optional[str] = None
    what_changed: str
    supporting_points: List[str] = Field(default_factory=list)
    supporting_evidence: List[str] = Field(default_factory=list)
    contradicting_points: List[str] = Field(default_factory=list)
    contradicting_evidence: List[str] = Field(default_factory=list)
    source_urls: List[str] = Field(default_factory=list)
    limitations_disclaimer: List[str] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    provider_used: str
    model_used: str
    stages: List[VerificationStageAudit] = Field(default_factory=list)
    audit_steps: Optional[List[Dict[str, Any]]] = None
    final_judgment: Optional[Dict[str, Any]] = None
    unverified_breakdown: Optional[UnverifiedBreakdown] = None
    metrics: Optional[VerificationMetrics] = None
    evidence_coverage: Optional[float] = None
    source_quality: Optional[float] = None
    claim_verification_confidence: Optional[float] = None
    reasoning_completeness: Optional[float] = None
    retrieved_sources_count: int = 0
    url_validated_sources_count: int = 0
    is_partial: bool = False
    error_notice: Optional[str] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    verification_timestamp: Optional[str] = None

    def model_post_init(self, __context: Any) -> None:
        if self.verdict is None:
            self.verdict = self.final_verdict
        if self.confidence is None:
            self.confidence = self.assessment_confidence
        if self.explanation is None:
            self.explanation = self.soundness_explanation
        if self.summary is None:
            self.summary = self.verdict_summary
        if not self.supporting_evidence and self.supporting_points:
            self.supporting_evidence = list(self.supporting_points)
        if not self.contradicting_evidence and self.contradicting_points:
            self.contradicting_evidence = list(self.contradicting_points)
        if not self.limitations and self.limitations_disclaimer:
            self.limitations = list(self.limitations_disclaimer)
        if not self.source_urls and self.sources:
            self.source_urls = [s.url for s in self.sources if s.url]
        if self.verification_timestamp is None:
            self.verification_timestamp = self.created_at
        self.retrieved_sources_count = len(self.sources)
        self.url_validated_sources_count = sum(1 for s in self.sources if getattr(s, "is_url_accessible", True))

        if self.metrics:
            if self.evidence_coverage is None:
                self.evidence_coverage = self.metrics.evidence_coverage
            if self.source_quality is None:
                self.source_quality = self.metrics.source_quality
            if self.claim_verification_confidence is None:
                self.claim_verification_confidence = self.metrics.claim_verification_confidence
            if self.reasoning_completeness is None:
                self.reasoning_completeness = self.metrics.reasoning_completeness

        if self.final_judgment is None:
            self.final_judgment = {
                "verdict": self.final_verdict,
                "assessment_confidence": self.assessment_confidence,
                "summary": self.verdict_summary,
                "what_changed": self.what_changed,
                "support_evidence": list(self.supporting_points or self.supporting_evidence),
                "counter_evidence": list(self.contradicting_points or self.contradicting_evidence),
                "assumptions": [],
                "unknowns": [],
                "limitations": list(self.limitations or self.limitations_disclaimer),
                "confidence_explanation": self.soundness_explanation
            }
        if self.audit_steps is None and self.stages:
            self.audit_steps = [
                {
                    "step_name": s.stage_name,
                    "duration_ms": s.duration_ms,
                    "summary": s.summary,
                    "details": s.details
                }
                for s in self.stages
            ]

